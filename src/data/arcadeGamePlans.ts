export function arcadeGamePlanById(id: string): ArcadeGamePlan | undefined {
  return ARCADE_GAME_PLANS.find((g) => g.id === id)
}

export function arcadeGamePlansByForm(): { form: CabinetForm; items: ArcadeGamePlan[] }[] {
  const order: CabinetForm[] = ['upright', 'candy', 'sitdown', 'twin', 'environmental', 'cocktail', 'bartop']
  return order
    .map((form) => ({ form, items: ARCADE_GAME_PLANS.filter((g) => g.form === form) }))
    .filter((g) => g.items.length > 0)
}
